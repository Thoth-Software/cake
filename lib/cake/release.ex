defmodule Cake.Release do
  @moduledoc """
  Database tasks for a release, where there is no Mix: `mix ecto.migrate` and
  `mix ecto.rollback` do not exist in the image `Dockerfile.release` builds.

  A release runs these through `bin/cake eval`, which loads the code and the
  runtime configuration (`config/runtime.exs`) without starting the
  application:

      bin/migrate                                               # Cake.Release.migrate/0
      bin/cake eval "Cake.Release.rollback(Cake.Repo, 20250101000000)"

  `bin/migrate` is `rel/overlays/bin/migrate`, which Mix copies into the
  release. Neither function starts `:cake`: `Ecto.Migrator.with_repo/3` starts
  the repo and what it needs, runs, and stops it again, so migrating reaches
  the database and none of the other services the running app needs.

  It still needs the app's environment, though. `bin/cake eval` evaluates
  `config/runtime.exs` before anything runs, and its prod block raises unless
  `DATABASE_URL`, `SECRET_KEY_BASE`, `OPENAI_KEY` and `BOOK_STORAGE_S3_BUCKET`
  are all set, whether or not the command uses them. Run `bin/migrate` with the
  environment the server gets.

  There is deliberately no seeding function. `priv/repo/seeds.exs` creates a
  login whose password is in the repository; a release never runs it, and the
  release image does not carry the file.

  Generated by `mix phx.gen.release` (#361). `ci/release_smoke.sh` runs
  `bin/migrate` inside the release image against an empty database on every
  pull request.
  """

  @app :cake

  @typedoc """
  What `Ecto.Migrator.with_repo/3` reports for one repo: the versions that were
  migrated (or rolled back), and the applications it started to do so.
  """
  @type result :: {:ok, [integer()], [atom()]}

  @doc """
  Applies every pending migration of every repo in `:ecto_repos`, in order.

  Returns one `t:result/0` per repo; the version list is empty when the
  database is already up to date. Raises when a repo cannot be started or a
  migration fails, so `bin/migrate` exits non-zero.
  """
  @spec migrate() :: [result()]
  def migrate do
    :ok = load_app()

    for repo <- repos() do
      {:ok, _, _} = Ecto.Migrator.with_repo(repo, &Ecto.Migrator.run(&1, :up, all: true))
    end
  end

  @doc """
  Rolls `repo` back down to and including the migration `version`.

  `version` is a migration's timestamp, as in its file name. Raises when the
  repo cannot be started or a migration's `down` fails.
  """
  @spec rollback(Ecto.Repo.t(), integer()) :: result()
  def rollback(repo, version) when is_atom(repo) and is_integer(version) do
    :ok = load_app()
    {:ok, _, _} = Ecto.Migrator.with_repo(repo, &Ecto.Migrator.run(&1, :down, to: version))
  end

  @spec repos() :: [Ecto.Repo.t()]
  defp repos do
    Application.fetch_env!(@app, :ecto_repos)
  end

  @spec load_app() :: :ok
  defp load_app do
    # Many platforms require SSL when connecting to the database
    {:ok, _started} = Application.ensure_all_started(:ssl)
    :ok = Application.ensure_loaded(@app)
  end
end
